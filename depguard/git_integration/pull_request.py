"""Publishing plan and gated publication. Two SEPARATE approvals: (1) push a new branch, (2) open the pull request.

`plan()` is read-only. `publish_branch()` and `open_pull_request()` re-check the base branch first and refuse to proceed
if it moved, if the target is the default branch, or if the approval phrase is missing. Nothing here merges or force-pushes.
"""
import re
from datetime import datetime, timezone

from .github import GitHubClient, GitHubError, valid_branch

PUBLISH_PHRASE = "PUBLISH"
PR_PHRASE = "OPEN PR"


def default_branch_name(finding_ids) -> str:
    stamp = datetime.now(timezone.utc).strftime("%Y%m%d-%H%M")
    tag = re.sub(r"[^a-z0-9]+", "-", "-".join(finding_ids)[:30].lower()).strip("-") or "fix"
    return f"depguard/{tag}-{stamp}"


def plan(client: GitHubClient, owner: str, repo: str, base_branch: str, patch_files: list, verification: dict, finding_ids=()) -> dict:
    """What would be published. Pure read: repo metadata + current base SHA."""
    info = client.repo(owner, repo)
    if not info["permissions"].get("push", False) and client.authenticated:
        write_note = "The token does not have push permission on this repository: publishing will fail. Fork the repository or use the local patch export."
    elif not client.authenticated:
        write_note = "Not authorized: publishing is unavailable. Use the local patch export."
    else:
        write_note = None
    base_sha = client.commit_sha(owner, repo, base_branch)
    return {"repository": info["full_name"], "default_branch": info["default_branch"], "base_branch": base_branch, "base_sha": base_sha,
            "proposed_branch": default_branch_name(finding_ids), "files": patch_files, "verification": verification,
            "can_publish": write_note is None, "publish_blocker": write_note,
            "warnings": ([] if verification.get("status") == "passed" else [f"Verification status is '{verification.get('status', 'not_run')}': this fix is not verified."])
                        + ([f"Base branch '{base_branch}' is the repository default; a new branch will be created, the default branch is never modified."] if base_branch == info["default_branch"] else [])}


def publish_branch(client: GitHubClient, owner: str, repo: str, plan_: dict, files: dict, message: str, confirm: str) -> dict:
    """Approval 1. Creates ONE commit on a NEW branch based on the SHA the user reviewed. Fails if the base branch moved."""
    if confirm != PUBLISH_PHRASE:
        raise GitHubError("invalid", f"explicit approval missing: type {PUBLISH_PHRASE}")
    if not plan_.get("can_publish"):
        raise GitHubError("permission", plan_.get("publish_blocker") or "publishing is not available")
    branch = plan_["proposed_branch"]
    valid_branch(branch)
    if branch in (plan_["default_branch"], plan_["base_branch"]):
        raise GitHubError("invalid", "refusing to write to the default or base branch")
    if set(files) != {f["path"] for f in plan_["files"]}:
        raise GitHubError("invalid", "the files to publish differ from the reviewed plan; review again")
    now = client.commit_sha(owner, repo, plan_["base_branch"])
    if now != plan_["base_sha"]:
        raise GitHubError("conflict", f"the base branch moved since you reviewed it ({plan_['base_sha'][:7]} -> {now[:7]}); re-run analysis and review again")
    return client.commit_to_new_branch(owner, repo, plan_["base_sha"], branch, files, message)


def pr_body(finding_titles, rationale, diff_summary, verification, gaps, capsule_ref) -> str:
    ver = verification.get("status", "not_run")
    lines = ["## Problem", *[f"- {t}" for t in finding_titles], "", "## Migration rationale", rationale or "(none provided)", "",
             "## Changes", diff_summary, "", "## Verification", f"Status: **{ver}**. " + ("Tests passing does not prove full compatibility." if ver == "passed" else "This change is NOT verified as working."),
             verification.get("summary", ""), "", "## Compatibility gaps / unresolved risks", *([f"- {g}" for g in gaps] or ["- none recorded"]), "",
             f"Generated by DepGuard AI. Capsule: {capsule_ref}. Opened only after explicit human approval; AI-generated changes should be reviewed before merging."]
    return "\n".join(lines)


def open_pull_request(client: GitHubClient, owner: str, repo: str, plan_: dict, branch_result: dict, title: str, body: str, confirm: str) -> dict:
    """Approval 2. Requires that the branch was actually pushed by approval 1."""
    if confirm != PR_PHRASE:
        raise GitHubError("invalid", f"explicit approval missing: type {PR_PHRASE}")
    if not branch_result or branch_result.get("branch") != plan_["proposed_branch"]:
        raise GitHubError("invalid", "no pushed branch matches this plan; publish the branch first")
    return client.create_pull_request(owner, repo, branch_result["branch"], plan_["base_branch"], title, body)
